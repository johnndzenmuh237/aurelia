/**
 * Builds public/js/icons.js — a small, offline-capable bundle of Lucide
 * icons (https://lucide.dev, ISC licence) so the UI uses one consistent
 * professional icon set with no CDN dependency (works inside the installed
 * PWA, offline).
 *
 *   npm i --no-save lucide-static
 *   node scripts/build-icons.js
 */
const fs = require("fs");
const path = require("path");

const NAMES = [
  "bell","bell-ring","check","check-check","x","menu","house","layout-dashboard","calendar","calendar-days","log-in","log-out",
  "arrow-right-to-line","arrow-left-from-line","bed-double","door-open","users","user","user-cog","user-plus","user-check","user-x",
  "star","building-2","clipboard-list","spray-can","wrench","utensils","wine","package","boxes","truck","store","receipt",
  "credit-card","wallet","banknote","coins","rotate-ccw","trending-down","briefcase","id-card","clock","calendar-clock","file-text",
  "chart-column","chart-pie","sparkles","moon","settings","shield-check","shield","key-round","lock","mail","message-square",
  "messages-square","send","megaphone","inbox","archive","search","plus","pencil","trash-2","eye","eye-off","download","smartphone",
  "info","triangle-alert","circle-check","circle-x","loader-circle","refresh-cw","chevron-down","chevron-right","chevron-left",
  "arrow-left","arrow-right","external-link","history","database","layers","shirt","glass-water","percent","party-popper","users-round",
  "hotel","snowflake","fan","wifi","car","circle","concierge-bell","badge-check","list-checks","scroll-text","activity","map-pin","tag","folder-open","square-pen","power",
  "user-round-cog","fingerprint","monitor-smartphone","table-2","chef-hat","beer","book-open","bed-single","clipboard-check","handshake",
];

const dir = path.join(process.argv[2] || "node_modules/lucide-static", "icons");
const out = {};
const missing = [];
for (const n of NAMES) {
  const f = path.join(dir, `${n}.svg`);
  if (!fs.existsSync(f)) { missing.push(n); continue; }
  const svg = fs.readFileSync(f, "utf8");
  out[n] = svg.replace(/<!--[\s\S]*?-->/g, "").replace(/<svg[\s\S]*?>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").replace(/> </g, "><").trim();
}
const js = `/* Lucide icons (ISC licence) — generated by scripts/build-icons.js. Do not edit by hand. */
(function () {
  const PATHS = ${JSON.stringify(out)};
  const Icons = {
    has: (name) => Object.prototype.hasOwnProperty.call(PATHS, name),
    /** Inline SVG string. Decorative by default (aria-hidden). */
    svg(name, opts) {
      const o = opts || {}; const size = o.size || 18;
      const body = PATHS[name] || PATHS["info"];
      return '<svg class="icon ' + (o.cls || "") + '" xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' + (o.stroke || 2) + '" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + body + '</svg>';
    },
    /** Replaces every <i data-icon="name" data-size="18"> under root. */
    hydrate(root) {
      (root || document).querySelectorAll("i[data-icon]").forEach((el) => {
        const tmp = document.createElement("span");
        tmp.innerHTML = Icons.svg(el.dataset.icon, { size: Number(el.dataset.size) || 18, cls: el.className });
        el.replaceWith(tmp.firstChild);
      });
    },
  };
  window.Icons = Icons;
})();
`;
fs.writeFileSync(path.join(__dirname, "..", "public", "js", "icons.js"), js);
console.log(`icons: ${Object.keys(out).length} written, missing: ${missing.join(", ") || "none"}`);
